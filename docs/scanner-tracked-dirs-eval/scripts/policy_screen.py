#!/usr/bin/env python3
"""Offline screen: which Git-tracked files would each scanner policy add,
per checkout, without building anything. Mirrors scanner.rs at d1333a9:
hidden entries are skipped by the walker before the denylist runs,
`.gitignore`/`.ignore` still apply (tracked-but-ignored files are excluded),
then the file-level rules (dot-files, DENYLIST_FILES, DENYLIST_SUFFIXES,
size caps, NUL-byte sniff) and, for the index, `language_for_path`.

Policies (only files under a directory skipped *by name* can change):
  tracked  any denylisted name except VCS dirs may be descended when it holds
           tracked files; inside it, only tracked files are kept
  narrow   the same, restricted to output-style names that are also common
           source directory names: build, dist, out, target

Noise heuristics per added file (reported, not used to filter): dependency
path (vendor/, node_modules/, third_party/), a generated-code marker in the
first 2 KB, minified shape (mean line length > 300).

usage: policy_screen.py <checkout dir>... > screen.jsonl
"""
import json
import os
import subprocess
import sys
from collections import Counter

DENYLIST_DIRS = {".git", ".hg", ".svn", "node_modules", "target", "dist", "build", "out",
                 ".next", ".nuxt", ".turbo", "__pycache__", ".venv", "venv", ".tox",
                 ".mypy_cache", ".pytest_cache", ".ruff_cache", "coverage", ".nyc_output",
                 "vendor", ".idea", ".vscode"}
VCS = {".git", ".hg", ".svn"}
NARROW = {"build", "dist", "out", "target"}
DENYLIST_FILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock",
                  "Pipfile.lock", "Cargo.lock", "uv.lock", "tsconfig.tsbuildinfo"}
DENYLIST_SUFFIXES = (".min.js", ".min.css", ".min.mjs", ".d.ts", ".generated.", "-gen.py")
MAX_BYTES, MAX_MD = 1_500_000, 64 * 1024
LANG_EXT = {"py", "pyi", "ts", "tsx", "js", "jsx", "mjs", "cjs", "rs", "go", "java", "rb", "rake",
            "gemspec", "php", "phtml", "c", "h", "cc", "cpp", "cxx", "hh", "hpp", "hxx", "md"}
GEN_MARKERS = (b"Code generated", b"@generated", b"DO NOT EDIT", b"auto-generated",
               b"autogenerated", b"This file was generated")


def indexable_name(name):
    ext = name.rsplit(".", 1)[-1] if "." in name else ""
    if name.endswith(".d.ts"):
        return False
    return ext in LANG_EXT or name in ("Rakefile", "Gemfile")


def git_z(repo, *args):
    out = subprocess.run(["git", "-C", repo, *args], capture_output=True, check=True).stdout
    return [p for p in out.decode("utf-8", "surrogateescape").split("\0") if p]


def screen(repo):
    tracked = git_z(repo, "ls-files", "-z")
    ignored = set(git_z(repo, "ls-files", "-z", "-ci", "--exclude-standard"))
    rec = dict(repo=repo, tracked_files=len(tracked))
    for policy in ("tracked", "narrow"):
        index_add, text_add = [], []
        for rel in tracked:
            parts = rel.split("/")
            dirs, name = parts[:-1], parts[-1]
            denied = [d for d in dirs if d in DENYLIST_DIRS]
            if not denied or rel in ignored or any(d.startswith(".") for d in dirs):
                continue
            allowed = NARROW if policy == "narrow" else DENYLIST_DIRS - VCS
            if not all(d in allowed for d in denied):
                continue
            if name.startswith(".") and not name.startswith(".env"):
                continue
            if name in DENYLIST_FILES or any(s in name for s in DENYLIST_SUFFIXES):
                continue
            path = os.path.join(repo, rel)
            try:
                size = os.path.getsize(path)
                with open(path, "rb") as fh:
                    head = fh.read(2048)
            except OSError:
                continue
            if size > MAX_BYTES or b"\0" in head[:1024]:
                continue
            entry = dict(path=rel, bytes=size, dir=denied[0])
            text_add.append(entry)
            if indexable_name(name) and (not name.endswith(".md") or size <= MAX_MD):
                with open(path, "rb") as fh:
                    body = fh.read()
                lines = body.count(b"\n") + 1
                entry["noise"] = [k for k, hit in (
                    ("dependency-path", any(d in ("vendor", "node_modules", "third_party") for d in dirs)),
                    ("generated-marker", any(m in head for m in GEN_MARKERS)),
                    ("minified", len(body) / lines > 300)) if hit]
                index_add.append(entry)
        rec[policy] = dict(
            index_files=len(index_add), index_bytes=sum(e["bytes"] for e in index_add),
            text_files=len(text_add), text_bytes=sum(e["bytes"] for e in text_add),
            by_dir=Counter(e["dir"] for e in index_add),
            by_ext=Counter(e["path"].rsplit(".", 1)[-1] for e in index_add),
            noisy=[e for e in index_add if e["noise"]][:50],
            noisy_count=sum(1 for e in index_add if e["noise"]),
            index_paths=sorted(e["path"] for e in index_add))
    return rec


if __name__ == "__main__":
    for repo in sys.argv[1:]:
        print(json.dumps(screen(repo)), flush=True)
