#!/usr/bin/env python3
"""Research-only developer-intent evidence extractor (issue #30).

Walks one indexed corpus (tracked files only, `git ls-files`) and emits every
candidate developer-intent text as a JSONL record with full provenance:

  {"eid", "file", "start_line", "end_line", "type", "lang", "symbol",
   "assoc", "heading", "text", "chars", "tags", "flags", "keep"}

Types
  docstring       Python function/class docstring (``ast``)            -> symbol
  module_doc      Python module docstring, Rust ``//!``, file-header
                  comment block before the first symbol                -> file
  leading_comment comment block directly above a symbol (<=1 blank gap)
                  incl. ``///``, JSDoc ``/** */``, Go doc comments      -> symbol
  inline_comment  comment block inside a symbol's span                 -> symbol (innermost)
  readme          README* chunk (split at headings)                    -> none
  doc             other .md/.rst/.txt/.adoc chunk under the repo       -> none
  changelog       CHANGES*/CHANGELOG*/HISTORY*/NEWS* chunk              -> none

``tags`` adds ``todo`` (TODO/FIXME/HACK/XXX/WORKAROUND) orthogonally to type.
``flags`` are noise/safety findings; ``keep`` is false for any record that a
production pipeline must not embed (secret-like, generated, vendored, lockfile,
build/cache path) and for pure noise (license header, directive-only,
commented-out code, too short). Symbol association comes from the corpus's
own OXIDE index (``symbols`` table, read-only), never from the extractor
guessing names.

The stable research id is sha1(file, type, symbol-or-heading, text, ordinal)
so it survives line shifts; it is research-only and unrelated to OXIDE's
symbol ids.

usage: extract_intent.py <repo_root> <out.jsonl> [--db index.db]
"""
import ast
import hashlib
import json
import math
import re
import sqlite3
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

MAX_CHARS = 1500     # split longer chunks (≈375 tokens at 4 chars/token)
MIN_CHARS = 12

CODE_EXT = {
    ".py": "python", ".rs": "rust", ".ts": "typescript", ".tsx": "typescript",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".go": "go", ".java": "java", ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp",
    ".hpp": "cpp", ".rb": "ruby", ".php": "php",
}
DOC_EXT = {".md", ".rst", ".txt", ".adoc", ".markdown"}
HASH_COMMENT = {"python", "ruby"}

VENDOR_RE = re.compile(r"(^|/)(vendor|vendored|third_party|third-party|node_modules|bower_components|"
                       r"dist|build|out|target|\.cache|__pycache__|site-packages|\.venv|venv|"
                       r"coverage|\.next|\.nuxt)(/|$)", re.I)
MINIFIED_RE = re.compile(r"\.min\.(js|css)$|\.bundle\.js$|\.map$", re.I)
LOCKFILE_RE = re.compile(r"(^|/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|Cargo\.lock|poetry\.lock|"
                         r"Pipfile\.lock|go\.sum|composer\.lock|Gemfile\.lock|uv\.lock)$")
GENERATED_RE = re.compile(r"@generated|do not edit|auto-?generated|autogenerated|generated by|"
                          r"this file was generated|code generated .* do not edit", re.I)
LICENSE_RE = re.compile(r"copyright|licensed under|spdx-license|permission is hereby granted|"
                        r"all rights reserved|apache license|mit license|gnu general public", re.I)
DIRECTIVE_RE = re.compile(r"^\s*(noqa|type:\s*ignore|pylint:\s*(disable|enable)|eslint-(disable|enable)|"
                          r"@ts-(ignore|expect-error|nocheck)|prettier-ignore|istanbul ignore|c8 ignore|"
                          r"fmt:\s*(off|on|skip)|isort:|pragma|nolint|go:build|\+build|"
                          r"clippy::|rustfmt::skip|-\*-.*-\*-|!/usr/bin|coding[:=]|"
                          r"region|endregion)", re.I)
TODO_RE = re.compile(r"\b(TODO|FIXME|HACK|XXX|WORKAROUND|KLUDGE)\b")
SECRET_RES = [
    ("aws_key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("private_key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("github_token", re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36,}\b")),
    ("slack_token", re.compile(r"\bxox[abposr]-[A-Za-z0-9-]{10,}")),
    ("openai_like_key", re.compile(r"\bsk-[A-Za-z0-9_-]{20,}")),
    ("google_api_key", re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b")),
    ("jwt", re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}")),
    ("assigned_secret", re.compile(r"(?i)\b(api[_-]?key|secret|passw(or)?d|token|auth)\b\s*[:=]\s*['\"]?"
                                   r"(?!\*+|x+|<|\{|\$|your|example|dummy|changeme|placeholder)[A-Za-z0-9_\-+/=]{12,}")),
    ("url_credentials", re.compile(r"[a-z][a-z0-9+.-]*://[^/\s:@]+:[^/\s:@]{3,}@", re.I)),
    ("high_entropy", re.compile(r"\b[A-Za-z0-9+/_-]{40,}={0,2}")),
]
EMAIL_RE = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
CODEISH_RE = re.compile(r"[;{}()=\[\]]|^\s*(def|class|import|from|return|if|for|while|let|const|var|fn|pub|func)\b")


def entropy(s):
    c = Counter(s)
    return -sum(v / len(s) * math.log2(v / len(s)) for v in c.values())


def secret_flags(text):
    out = []
    for name, rx in SECRET_RES:
        for m in rx.finditer(text):
            tok = m.group(0)
            if name == "high_entropy":
                # identifiers/paths are long but low-entropy; require mixed classes and entropy.
                if entropy(tok) < 4.3 or not (re.search(r"\d", tok) and re.search(r"[A-Z]", tok)
                                              and re.search(r"[a-z]", tok)):
                    continue
            out.append(name)
            break
    return sorted(set(out))


def is_commented_code(lines):
    if len(lines) < 2:
        return False
    codey = sum(1 for l in lines if CODEISH_RE.search(l) and len(re.findall(r"[A-Za-z]{3,}", l)) <= 6)
    return codey / len(lines) >= 0.6


def squash(s):
    return re.sub(r"\s+", " ", s).strip()


def git_files(root):
    out = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=True).stdout
    return [p for p in out.decode("utf-8", "replace").split("\0") if p]


def load_symbols(db):
    by_file = defaultdict(list)
    if not db or not Path(db).exists():
        return by_file
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    for f, qn, kind, s, e in con.execute("select file, qualified_name, kind, start_line, end_line from symbols"):
        by_file[f].append((s, e, qn, kind))
    for v in by_file.values():
        v.sort()
    return by_file


# ---------------------------------------------------------------------------
# comment blocks (every language; Python only for '#' comments)
# ---------------------------------------------------------------------------

def comment_blocks(lang, lines):
    """Return (start, end, [clean lines], kind) for contiguous comment blocks
    (1-based inclusive lines). Naive about markers inside strings."""
    blocks = []
    i, n = 0, len(lines)
    line_prefixes = ("#",) if lang in HASH_COMMENT else ("//",)
    while i < n:
        t = lines[i].strip()
        if lang not in HASH_COMMENT and t.startswith("/*"):
            start = i
            body = []
            kind = "doc" if t.startswith("/**") else "plain"
            while True:
                seg = re.sub(r"^/\*+!?", "", lines[i].strip())
                closed = "*/" in seg
                seg = re.sub(r"^\*+\s?", "", seg.split("*/")[0].strip())
                body.append(seg)
                if closed or i + 1 >= n:
                    break
                i += 1
            blocks.append((start + 1, i + 1, body, kind))
            i += 1
            continue
        if t.startswith(line_prefixes) and not (lang == "rust" and t.startswith("#[")):
            if lang in HASH_COMMENT and t.startswith("#!") and i == 0:
                i += 1
                continue
            start = i
            body = []
            kind = "plain"
            while i < n:
                t2 = lines[i].strip()
                if not t2.startswith(line_prefixes):
                    break
                if t2.startswith(("///", "//!")):
                    kind = "doc"
                body.append(re.sub(r"^(///?!?|#+)\s?", "", t2))
                i += 1
            blocks.append((start + 1, i, body, kind))
            continue
        i += 1
    return blocks


def enclosing(syms, line):
    best = None
    for s, e, qn, kind in syms:
        if s <= line <= e and (best is None or (e - s) < (best[1] - best[0])):
            best = (s, e, qn, kind)
    return best


def next_symbol_after(syms, end_line, lines, lang):
    """Symbol starting within one blank line (skipping attributes/decorators) after end_line."""
    j = end_line  # 0-based index of the line after the block
    gap = 0
    while j < len(lines):
        t = lines[j].strip()
        if not t:
            gap += 1
            if gap > 1:
                return None
            j += 1
            continue
        if (lang == "rust" and t.startswith("#[")) or (lang in ("python", "typescript", "javascript") and t.startswith("@")):
            j += 1
            continue
        break
    cands = [x for x in syms if end_line + 1 <= x[0] <= j + 1]
    if not cands:
        return None
    return max(cands, key=lambda x: x[1] - x[0])


# ---------------------------------------------------------------------------
# Python via ast
# ---------------------------------------------------------------------------

def _lead(expr):
    """Blank lines stripped from the front by ast.get_docstring(clean=True),
    so emitted spans start at the docstring's first text line."""
    raw = expr.value.value if isinstance(expr.value, ast.Constant) and isinstance(expr.value.value, str) else ""
    n = 0
    for line in raw.split("\n"):
        if line.strip():
            break
        n += 1
    return n


def python_docstrings(src):
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError):
        return None
    out = []
    mod = ast.get_docstring(tree, clean=True)
    if mod and tree.body and isinstance(tree.body[0], ast.Expr):
        n = tree.body[0]
        out.append(("module_doc", n.lineno + _lead(n), n.end_lineno, mod, None))
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            d = ast.get_docstring(node, clean=True)
            if d and node.body and isinstance(node.body[0], ast.Expr):
                b = node.body[0]
                out.append(("docstring", b.lineno + _lead(b), b.end_lineno, d, node.lineno))
    return out


# ---------------------------------------------------------------------------
# docs chunking
# ---------------------------------------------------------------------------

RST_ADORN = "=-~^\"'`#*+"


def doc_chunks(path, lines):
    """Split at markdown '#' headings or rst underlined headings; keep the heading path."""
    is_rst = path.endswith(".rst")
    heads = []  # (line_idx, level, title)
    in_fence = False
    for i, l in enumerate(lines):
        if l.strip().startswith("```"):
            in_fence = not in_fence
        if in_fence:
            continue
        m = re.match(r"^(#{1,6})\s+(.*)", l)
        if m and not is_rst:
            heads.append((i, len(m.group(1)), m.group(2).strip()))
        elif is_rst and i + 1 < len(lines) and l.strip() and not l.startswith(" "):
            u = lines[i + 1].strip()
            if len(u) >= 3 and u[0] in RST_ADORN and u == u[0] * len(u) and len(u) >= len(l.strip()) * 0.6:
                heads.append((i, RST_ADORN.index(u[0]) + 1, l.strip()))
    bounds = [h[0] for h in heads] + [len(lines)]
    sections = []
    if not heads or heads[0][0] > 0:
        sections.append((0, bounds[0] if heads else len(lines), ""))
    stack = []
    for k, (i, level, title) in enumerate(heads):
        stack = [s for s in stack if s[0] < level] + [(level, title)]
        sections.append((i, bounds[k + 1], " > ".join(t for _, t in stack)))
    out = []
    for s, e, heading in sections:
        cur, cur_start, size = [], s, 0
        for j in range(s, e):
            cur.append(lines[j])
            size += len(lines[j]) + 1
            if size >= MAX_CHARS and not lines[j].strip():
                out.append((cur_start + 1, j + 1, heading, "\n".join(cur)))
                cur, cur_start, size = [], j + 1, 0
        if cur:
            out.append((cur_start + 1, e, heading, "\n".join(cur)))
    return out


# ---------------------------------------------------------------------------

def classify_path(path):
    flags = []
    if VENDOR_RE.search(path):
        flags.append("vendored_or_build_path")
    if MINIFIED_RE.search(path):
        flags.append("minified_or_map")
    if LOCKFILE_RE.search(path):
        flags.append("lockfile")
    return flags


def split_lines(numbered):
    """Group (line_no, text) pairs into parts of at most MAX_CHARS on line
    boundaries; a single over-long line is cut but keeps its own line number.
    Returns [(start_line, end_line, text)]."""
    parts, cur = [], []
    size = 0
    for n, t in numbered:
        while len(t) > MAX_CHARS:
            if cur:
                parts.append(cur)
                cur, size = [], 0
            parts.append([(n, t[:MAX_CHARS])])
            t = t[MAX_CHARS:]
        if cur and size + len(t) + 1 > MAX_CHARS:
            parts.append(cur)
            cur, size = [], 0
        cur.append((n, t))
        size += len(t) + 1
    if cur:
        parts.append(cur)
    return [(p[0][0], p[-1][0], "\n".join(t for _, t in p)) for p in parts]


SKIP_DOC_NAMES = re.compile(r"^(license|licence|copying|notice|authors|contributors|codeowners|"
                            r"requirements|constraints)", re.I)


def main():
    root = Path(sys.argv[1]).resolve()
    out_path = sys.argv[2]
    db = sys.argv[sys.argv.index("--db") + 1] if "--db" in sys.argv else str(root / ".oxide/index.db")
    syms_by_file = load_symbols(db)
    records = []
    ordinal = defaultdict(int)

    def emit(file, typ, lang, sym, heading, numbered, extra_flags, file_generated):
        """numbered: [(line_no, text)]. Long content is split on line boundaries
        so every emitted part carries the line span of its own text."""
        is_docfile = typ in ("readme", "doc", "changelog")
        for s, e, raw in split_lines(numbered):
            part = raw.strip() if is_docfile else squash(raw)
            if not part:
                continue
            flags = list(extra_flags)
            if file_generated:
                flags.append("generated_file")
            if GENERATED_RE.search(part):
                flags.append("generated_marker")
            flags += ["secret:" + x for x in secret_flags(part)]
            if EMAIL_RE.search(part):
                flags.append("email")  # personal data: never embedded
            if not is_docfile:
                if LICENSE_RE.search(part):
                    flags.append("license")
                if DIRECTIVE_RE.match(part) or len(re.findall(r"[A-Za-z]{2,}", part)) < 3:
                    flags.append("directive_or_trivial")
                if is_commented_code([l for l in raw.splitlines() if l.strip()]):
                    flags.append("commented_code")
            if len(part) < MIN_CHARS:
                flags.append("too_short")
            unsafe = any(f.startswith("secret:") or f in ("generated_file", "generated_marker", "vendored_or_build_path",
                                                             "minified_or_map", "lockfile", "not_indexed", "email")
                         for f in flags)
            noise = any(f in ("license", "directive_or_trivial", "commented_code", "too_short") for f in flags)
            key = (file, typ, sym or heading or "", part)
            ordinal[key] += 1
            eid = "ev:" + hashlib.sha1("\0".join(map(str, key + (ordinal[key],))).encode()).hexdigest()[:16]
            records.append({
                "eid": eid, "file": file, "start_line": s, "end_line": e, "type": typ, "lang": lang,
                "symbol": sym, "assoc": "symbol" if sym else ("none" if is_docfile else "file"),
                "heading": heading, "text": part, "chars": len(part),
                "tags": ["todo"] if TODO_RE.search(part) else [],
                "flags": sorted(set(flags)), "keep": not unsafe and not noise,
            })

    for rel in git_files(root):
        p = root / rel
        if not p.is_file() or p.is_symlink():
            continue
        ext = p.suffix.lower()
        name = p.name.lower()
        stem = p.stem.lower()
        is_doc = ext in DOC_EXT or (ext == "" and stem in ("readme", "changelog", "changes", "news", "history"))
        lang = CODE_EXT.get(ext)
        if not is_doc and not lang:
            continue
        try:
            raw = p.read_bytes()
        except OSError:
            continue
        if b"\0" in raw[:1024] or len(raw) > 2_000_000:
            continue
        src = raw.decode("utf-8", "replace")
        lines = src.splitlines()
        pflags = classify_path(rel)
        file_generated = bool(GENERATED_RE.search("\n".join(lines[:15])))
        if is_doc:
            if SKIP_DOC_NAMES.match(name) or "/requirements" in rel:
                continue
            typ = "readme" if name.startswith("readme") else \
                "changelog" if re.match(r"(changes|changelog|history|news|release)", name) else "doc"
            for s, e, heading, text in doc_chunks(rel, lines):
                if len(text.strip()) >= MIN_CHARS:
                    emit(rel, typ, "doc", None, heading, list(enumerate(text.split("\n"), s)),
                         pflags, file_generated)
            continue
        syms = syms_by_file.get(rel, [])
        if rel not in syms_by_file:
            pflags = pflags + ["not_indexed"]  # OXIDE excluded/unsupported: inventory only
        first_sym = min((s for s, e, qn, k in syms if k not in ("module", "file")), default=10**9)
        # Header = comment blocks before the first line of real code (not just before the first symbol:
        # macro-generated tests and top-level statements are not symbols).
        cmark = ("#",) if lang in HASH_COMMENT else ("//", "/*", "*")
        first_code = next((k + 1 for k, l in enumerate(lines)
                           if l.strip() and not l.strip().startswith(cmark)), 10**9)
        first_sym = min(first_sym, first_code)
        claimed = set()
        if lang == "python":
            for typ, s, e, text, owner in python_docstrings(src) or []:
                sym = None
                if typ == "docstring":
                    pick = min((x for x in syms if x[0] <= owner and x[1] >= e and x[3] not in ("module", "file")),
                               key=lambda x: x[1] - x[0], default=None)
                    sym = pick[2] if pick else None
                emit(rel, typ, lang, sym, None, list(enumerate(text.split("\n"), s)), pflags, file_generated)
                claimed.update(range(s, e + 1))
        for s, e, body, kind in comment_blocks(lang, lines):
            if any(l in claimed for l in range(s, e + 1)):
                continue
            numbered = [(s + k, b) for k, b in enumerate(body) if b.strip()]
            if not numbered:
                continue
            inner = enclosing([x for x in syms if x[3] not in ("module", "file")], s)
            nxt = next_symbol_after([x for x in syms if x[3] not in ("module", "file")], e, lines, lang)
            if lang == "rust" and all(lines[k - 1].strip().startswith(("//!", "/*!")) for k in range(s, e + 1)):
                typ, sym = "module_doc", None
            elif nxt and (inner is None or nxt[0] <= inner[1]):
                typ, sym = "leading_comment", nxt[2]
            elif inner and inner[0] < s:
                typ, sym = "inline_comment", inner[2]
            elif e < first_sym:
                typ, sym = "module_doc", None
            else:
                typ, sym = "inline_comment", None  # free-floating comment at file scope
            emit(rel, typ, lang, sym, None, numbered, pflags, file_generated)

    with open(out_path, "w") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")
    print(f"{root.name}: {len(records)} records, keep={sum(r['keep'] for r in records)}", file=sys.stderr)


if __name__ == "__main__":
    main()
